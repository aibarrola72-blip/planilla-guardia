alter table public.sectores    enable row level security;
alter table public.cargos      enable row level security;
alter table public.turnos      enable row level security;
alter table public.personas    enable row level security;
alter table public.vacaciones  enable row level security;
alter table public.libres      enable row level security;
alter table public.plan_mensual enable row level security;
alter table public.perfiles    enable row level security;

-- Solo jefes pueden ver/escribir la operación.
create policy "jefes gestionan unidades"    on public.unidades    for all to authenticated using (public.es_jefe()) with check (public.es_jefe());
create policy "jefes gestionan sectores"    on public.sectores    for all to authenticated using (public.es_jefe()) with check (public.es_jefe());
create policy "jefes gestionan cargos"      on public.cargos      for all to authenticated using (public.es_jefe()) with check (public.es_jefe());
create policy "jefes gestionan turnos"      on public.turnos      for all to authenticated using (public.es_jefe()) with check (public.es_jefe());
create policy "jefes gestionan personal"    on public.personas    for all to authenticated using (public.es_jefe()) with check (public.es_jefe());
create policy "jefes gestionan vacaciones"  on public.vacaciones  for all to authenticated using (public.es_jefe()) with check (public.es_jefe());
create policy "jefes gestionan libres"      on public.libres      for all to authenticated using (public.es_jefe()) with check (public.es_jefe());
create policy "jefes gestionan plan"        on public.plan_mensual for all to authenticated using (public.es_jefe()) with check (public.es_jefe());

-- Cada usuario solo ve su propio perfil.
create policy "perfil propio" on public.perfiles
  for all to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

