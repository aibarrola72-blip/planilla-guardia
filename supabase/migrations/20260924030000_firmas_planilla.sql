on conflict (clave) do nothing;

-- RLS: solo lectura para autenticados; escritura SOLO vía backend
-- (service_role bypasea el RLS). La app móvil no usa esta tabla.
alter table public.firmas_planilla enable row level security;

drop policy if exists "firmas.read" on public.firmas_planilla;
create policy "firmas.read" on public.firmas_planilla
  for select to authenticated
  using (es_admin() or es_jefe_enfermeria() or es_jefe());

