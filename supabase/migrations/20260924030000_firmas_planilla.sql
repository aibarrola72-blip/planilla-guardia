-- ============================================================
-- INERAM - Firmas al pie de la planilla
-- Los nombres de las firmas del reporte salen de esta tabla:
--   - por persona  (persona_id): nombre de la persona asignada
--   - por cargo    (cargo_id)  : cada personal ACTIVO con ese cargo
--   - nombre fijo  (nombre_fijo): texto directo (fallback)
-- La firma es INDEPENDIENTE de las unidades seleccionadas en el
-- reporte (ej. "Jefa de Sala V y Urgencias Pediátricas" firma
-- aún cuando el reporte se imprima de una sola unidad).
-- ============================================================

create table if not exists public.firmas_planilla (
  id          bigint generated by default as identity primary key,
  clave       text not null unique,             -- jefe_unidad / jefe_enfermeria / jefe_personal
  subtitulo   text not null default '',         -- texto bajo el nombre
  cargo_id    bigint references public.cargos(id) on delete set null,
  persona_id  bigint references public.personas(id) on delete set null,
  nombre_fijo text,                             -- nombre manual si no hay persona/cargo
  orden       bigint not null default 0,
  activo      boolean not null default true,
  updated_at  timestamptz not null default now()
);

